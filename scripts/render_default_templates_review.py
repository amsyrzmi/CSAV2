def _cell(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def _days(n: int) -> str:
    return f"{n} day" if n == 1 else f"{n} days"


def _when(step: TemplateStep) -> str:
    anchor = _ANCHORS[step.anchor]
    offset = step.due_offset_days
    if offset == 0:
        when = f"on {anchor}"
    elif offset > 0:
        when = f"{_days(offset)} after {anchor}"
    else:
        when = f"{_days(-offset)} before {anchor}"
    if step.anchor == "probation_end":
        when += " (waiting for a date until HR sets it)"
    return when[0].upper() + when[1:]


def _who(template: TemplateCreate, step: TemplateStep) -> str:
    if step.auto_check == "access_removed":
        return "The system (when the leaver is finished, the day after the last day)"
    if step.owner_role == "employee":
        return "The new hire" if template.kind == "onboarding" else "The leaver"
    if step.owner_role == "manager":
        return "The person's manager"
    return "HR team"


def _source(note: SourceNote) -> tuple[str, str, str, str]:
    return (
        _cell(note.body),
        _cell(note.url) if note.url else "none",
        note.checked_on.isoformat(),
        _CONFIDENCE[note.confidence],
    )


def _template_section(template: TemplateCreate) -> str:
    lines = [
        f"## {template.name}",
        "",
        "| # | Step | Who does it | When it is due | Required | Approval | Note | Source | URL "
        "| Checked | Confidence |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for ordinal, step in enumerate(template.steps, start=1):
        key = f"{template.kind}:{ordinal}"
        body, url, checked, confidence = _source(DEFAULT_TEMPLATE_SOURCES[key])
        approval = _APPROVAL[step.approval_by] if step.approval_by else "none"
        lines.append(
            f"| {ordinal} | {_cell(step.title_en)} | {_who(template, step)} | {_when(step)} "
            f"| {'Required' if step.required else 'Optional'} | {approval} "
            f"| {_cell(step.reference_note)} | {body} | {url} | {checked} | {confidence} |"
        )
    lines += ["", f"### {template.name}: what each step asks", ""]
    for ordinal, step in enumerate(template.steps, start=1):
        lines.append(f"{ordinal}. **{_cell(step.title_en)}.** {_cell(step.description_en)}")
    return "\n".join(lines) + "\n"


def render() -> str:
    """The review document as committed: header, one section per template, then the lists."""
    parts = [_HEADER]
    parts += [_template_section(t) for t in DEFAULT_TEMPLATES]
    parts += [_LEFT_OUT, _UNCONFIRMED, _QUESTIONS, _SIGN_OFF]
    return "\n".join(parts)


def main() -> None:
    """Write the review document to docs/hr/DEFAULT_TEMPLATES_REVIEW.md."""
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(OUTPUT.parents[2])}")


if __name__ == "__main__":
    main()
